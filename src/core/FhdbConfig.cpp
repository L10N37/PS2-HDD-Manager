FhdbConfig::FhdbConfig() = default;

std::string FhdbConfig::trim(const std::string &value)
{
    const auto first = std::find_if_not(value.begin(), value.end(), [](unsigned char character) {
        return std::isspace(character) != 0;
    });
    const auto last = std::find_if_not(value.rbegin(), value.rend(), [](unsigned char character) {
        return std::isspace(character) != 0;
    }).base();
    return first < last ? std::string(first, last) : std::string();
}

FhdbConfig::Line FhdbConfig::parseLine(const std::string &text)
{
    Line line;
    line.raw = text;
    const std::string cleaned = trim(text);
    if (cleaned.empty() || cleaned.front() == '#')
        return line;

    const std::size_t equals = text.find('=');
    if (equals == std::string::npos)
        return line;
    line.key = trim(text.substr(0, equals));
    if (line.key.empty())
        return line;
    line.value = trim(text.substr(equals + 1));
    line.assignment = true;
    return line;
}

FhdbConfig::Line FhdbConfig::assignment(const std::string &key, const std::string &value)
{
    Line line;
    line.assignment = true;
    line.key = key;
    line.value = value;
    line.raw = key + " = " + value;
    return line;
}

FhdbConfig FhdbConfig::Parse(const std::string &text)
{
    FhdbConfig result;
    result.newline = text.find("\r\n") != std::string::npos ? "\r\n" : "\n";
    result.finalNewline = !text.empty() && text.back() == '\n';

    std::size_t position = 0;
    while (position < text.size())
    {
        const std::size_t end = text.find('\n', position);
        const std::size_t length = end == std::string::npos ? text.size() - position : end - position;
        std::string line = text.substr(position, length);
        if (!line.empty() && line.back() == '\r')
            line.pop_back();
        result.lines.push_back(parseLine(line));
        if (end == std::string::npos)
            break;
        position = end + 1;
    }
    return result;
}

